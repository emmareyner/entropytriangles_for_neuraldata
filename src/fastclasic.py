"""
fastclasic.py: vectorised CLasIC core for small contexts (up to 63 objects; sizes up to
40 x 40 have been used).

Gives the same numbers as fca.compute_concepts + calculate_entropies.sentropies /
jentropies (checked by check_against_reference(), which runs before every experiment),
but 100–1000× faster, which is what makes the random references (hundreds of thousands
of contexts) feasible.

  concepts(C)      -> E (concepts × objects), I (concepts × attributes), uint8
                      extents = family generated by intersecting attribute columns
                      (closed under intersection, plus the full object set)
  smet(M)          -> per-variable (ΔH', M', VI') normalised, and the @AVERAGE row
  cmet(E, I)       -> (ΔH', I', H'(X|Y)) for X and (ΔH', I', H'(Y|X)) for Y
  curveball(C, rng)-> random context with the same row and column sums
"""

from __future__ import annotations

import math

import numpy as np


# ---------------------------------------------------------------- concepts

def concepts(C):
    C = np.asarray(C, dtype=np.uint8)
    n, m = C.shape
    w = (np.uint64(1) << np.arange(n, dtype=np.uint64))
    cols = (C.astype(np.uint64) * w[:, None]).sum(axis=0).astype(np.uint64)   # extent of each attribute
    full = np.uint64((1 << n) - 1)
    S = np.array([full], dtype=np.uint64)
    for c in cols:
        S = np.unique(np.concatenate([S, S & c]))
    I = ((S[:, None] & cols[None, :]) == S[:, None]).astype(np.uint8)
    E = ((S[:, None] >> np.arange(n, dtype=np.uint64)[None, :]) & np.uint64(1)).astype(np.uint8)
    return E, I


# ---------------------------------------------------------------- entropies

def _codes(M):
    M = np.asarray(M, dtype=np.uint64)
    return (M << np.arange(M.shape[1], dtype=np.uint64)[None, :]).sum(axis=1)


def _H(codes):
    _, c = np.unique(codes, return_counts=True)
    if len(c) == 1:
        return 0.0
    p = c / c.sum()
    return float(-(p * np.log2(p)).sum())


def smet(M):
    """Rows of normalised (ΔH', M', VI') per column, plus the @AVERAGE row (last)."""
    M = np.asarray(M, dtype=np.uint8)
    n, m = M.shape
    codes = _codes(M)
    Hall = _H(codes)
    HU = np.empty(m); HP = np.empty(m); VI = np.empty(m)
    for j in range(m):
        col = M[:, j]
        k = col.sum()
        HU[j] = 1.0                     # log2(max(2, n_distinct)) = 1 for binary columns
        if k in (0, n):
            HP[j] = 0.0
        else:
            q = k / n
            HP[j] = -(q * math.log2(q) + (1 - q) * math.log2(1 - q))
        VI[j] = HP[j] if m == 1 else Hall - _H(codes & ~np.uint64(1 << j))
    out = np.column_stack([HU - HP, HP - VI, VI])            # HU = 1 -> already normalised
    avg = np.array([(HU - HP).sum(), (HP - VI).sum(), VI.sum()]) / HU.sum()
    return np.vstack([out, avg])


def cmet(E, I):
    E = np.asarray(E, dtype=np.uint8); I = np.asarray(I, dtype=np.uint8)
    HUx = float(sum(1.0 for j in range(E.shape[1]) if 0 < E[:, j].sum() < len(E)))
    HUy = float(sum(1.0 for j in range(I.shape[1]) if 0 < I[:, j].sum() < len(I)))
    cx, cy = _codes(E), _codes(I)
    Hx, Hy = _H(cx), _H(cy)
    Hxy = _H((cx << np.uint64(I.shape[1])) | cy)
    Hx_y, Hy_x = Hxy - Hy, Hxy - Hx
    Iv = 0.5 * ((Hx - Hx_y) + (Hy - Hy_x))
    X = np.array([HUx - Hx, Iv, Hx_y]) / HUx if HUx > 0 else np.zeros(3)
    Y = np.array([HUy - Hy, Iv, Hy_x]) / HUy if HUy > 0 else np.zeros(3)
    return X, Y


def pooled(contexts):
    """Stack the concepts of every context; return SMET neurons (intents), SMET odorants
    (extents), CMET X, CMET Y and the per-context (E, I)."""
    EI = [concepts(C) for C in contexts]
    E = np.vstack([e for e, _ in EI]); I = np.vstack([i for _, i in EI])
    return smet(I), smet(E), *cmet(E, I), EI


# ---------------------------------------------------------------- swap null

def curveball(C, rng, n_trades=None):
    """Curveball algorithm (Strona et al., 2014): uniform sample of the binary matrices with
    the same row sums and column sums as C (same null model as swap randomisation, Gionis
    et al., 2007, with faster mixing). Rows are handled as bitmasks."""
    C = np.asarray(C, dtype=np.uint8)
    n, m = C.shape
    if n < 2:
        return C.copy()
    rows = [int(v) for v in (C.astype(np.int64) << np.arange(m)[None, :]).sum(axis=1)]
    n_trades = n_trades or 20 * n
    a_idx = rng.integers(0, n, n_trades)
    b_idx = (a_idx + rng.integers(1, n, n_trades)) % n          # b != a
    keys = rng.random((n_trades, m))
    for t in range(n_trades):
        a, b = a_idx[t], b_idx[t]
        A, B = rows[a], rows[b]
        a_only, b_only = A & ~B, B & ~A
        if not a_only or not b_only:
            continue
        pool = [j for j in range(m) if (a_only | b_only) >> j & 1]
        k = bin(a_only).count("1")
        pool.sort(key=keys[t].__getitem__)
        shared = A & B
        na = shared
        for j in pool[:k]:
            na |= 1 << j
        nb = shared
        for j in pool[k:]:
            nb |= 1 << j
        rows[a], rows[b] = na, nb
    r = np.array(rows, dtype=np.int64)
    return ((r[:, None] >> np.arange(m)[None, :]) & 1).astype(np.uint8)


# ---------------------------------------------------------------- checks

def check_against_reference(n_checks=300, seed=1):
    """fastclasic == fca.compute_concepts + calculate_entropies on random contexts."""
    import fca
    from calculate_entropies import sentropies, jentropies
    rng = np.random.default_rng(seed)
    worst = 0.0
    for t in range(n_checks):
        n, m = int(rng.integers(2, 24)), int(rng.integers(1, 12))
        C = (rng.random((n, m)) < rng.random()).astype(int)
        E, I = concepts(C)
        _, E2, I2, _, _ = fca.compute_concepts(C)
        assert {tuple(r) for r in I} == {tuple(int(x) for x in r) for r in I2}, "intents differ"
        assert len(I) == len(I2), "number of concepts differs"
        for M in (I, E):
            ref = sentropies(M)[["DeltaH_norm", "M_norm", "VI_norm"]].to_numpy(float)
            worst = max(worst, float(np.abs(smet(M) - ref).max()))
        ref = jentropies(E, I)[["DeltaH_norm", "I_norm", "Hcond_norm"]].to_numpy(float)
        x, y = cmet(E, I)
        worst = max(worst, float(np.abs(np.vstack([x, y]) - ref[:2]).max()))
        if t < 50:   # curveball keeps margins
            R = curveball(C, rng)
            assert (R.sum(0) == C.sum(0)).all() and (R.sum(1) == C.sum(1)).all()
    assert worst < 1e-9, worst
    return worst
